def test_string_hash():
    assert java_string_hash("") == 0
    assert java_string_hash("a") == 97
    assert java_string_hash("Aa") == java_string_hash("BB") == 2112
    assert java_string_hash("polygenelubricants") == -2 ** 31  # Integer.MIN_VALUE
    assert java_string_hash("Å") == 0xC5
    assert java_string_hash("\U0001F600") == 0xD83D * 31 + 0xDE00  # two UTF-16 code units


def test_hash_codes_and_spread():
    assert java_hash_code(None) == 0
    assert java_hash_code(-5) == -5
    assert java_hash_code(2 ** 31) == -2 ** 31  # int32 wrap
    assert java_hash_code(Obj("x")) == IDENTITY_HASH == 1
    assert spread(0x12345678) == 0x12345678 ^ 0x1234
    assert spread(-1) == -1 ^ 0xFFFF


def test_identity_keys_insertion_order_up_to_ten():
    objs = [Obj("o%d" % i) for i in range(12)]
    s = JavaHashSet()
    for o in objs[:10]:
        s.add(o)
    assert s.to_array() == objs[:10]
    assert s.bin_layout()[0][1] == "list"


def test_identity_keys_treeify_at_eleven():
    objs = [Obj("o%d" % i) for i in range(12)]
    s = JavaHashSet()
    for o in objs[:11]:
        s.add(o)
    assert [o.label for o in s] == "o3 o0 o1 o2 o4 o5 o6 o7 o8 o9 o10".split()
    assert s.table_capacity() == 64 and s.bin_layout()[0][1] == "tree"
    s.add(objs[11])
    s.remove(objs[0])
    assert [o.label for o in s] == "o7 o3 o1 o2 o4 o5 o6 o8 o9 o10 o11".split()


def test_null_key_and_integer_bins():
    s = JavaHashSet()
    for k in (17, 1, 33, None, 16):
        s.add(k)
    assert s.to_array() == [None, 16, 17, 1, 33]


def test_colliding_strings_keep_list_order_below_threshold():
    s = JavaHashSet()
    for k in ("BB", "Aa", "AaAa", "BBBB", "AaBB", "BBAa", "SV", "A"):
        s.add(k)
    assert s.to_array() == ["BB", "Aa", "A", "SV", "AaAa", "BBBB", "AaBB", "BBAa"]


def test_hashmap_api():
    m = JavaHashMap()
    assert m.put(3, "a") is None
    assert m.put(19, "b") is None
    assert m.put(3, "c") == "a"  # existing key keeps its position
    assert m.keys() == [3, 19] and m.values() == ["c", "b"]
    assert m.get(19) == "b" and m.contains_key(3) and 19 in m and len(m) == 2
    assert m.remove(3) == "c" and m.remove(3) is None
    assert m.items() == [(19, "b")]
    m.clear()
    assert m.is_empty() and m.table_capacity() == 16


def test_resize_splits_preserving_order():
    m = JavaHashMap()
    keys = [1, 17, 33, 49, 2, 18, 3, 4, 5, 6, 7, 8, 9]  # 13 > threshold 12 -> resize to 32
    for k in keys:
        m.put(k, k)
    assert m.table_capacity() == 32
    assert m.keys() == [1, 33, 2, 3, 4, 5, 6, 7, 8, 9, 17, 49, 18]


