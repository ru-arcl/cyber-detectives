from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys

import pytest

from cyber_detectives.compat.javahash import (IDENTITY_HASH, JavaHashMap, JavaHashSet, java_hash_code,
                                              java_string_hash, spread)

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
FIXTURE = os.path.join(HERE, "fixtures", "golden", "javahash.json")


class Obj:
    """A key with identity hashCode/equals, like projects.cyberDetective.Vertex."""

    def __init__(self, label):
        self.label = label

    def __repr__(self):
        return self.label


def _digest(line):
    return hashlib.sha1(line.encode("utf-8")).hexdigest()[:12]


def _replay(script):
    objs = {}
    st = JavaHashSet()
    kind = script["kind"]

    def key(tok):
        if tok == "null":
            return None
        if kind == "obj":
            return objs.setdefault(tok, Obj(tok))
        return int(tok) if kind == "int" else tok

    def label(k):
        if k is None:
            return "null"
        return k.label if kind == "obj" else str(k)

    for i, op in enumerate(script["ops"]):
        k = key(op[1:])
        if op[0] == "+":
            st.add(k)
        else:
            st.remove(k)
        yield i, " ".join(label(x) for x in st)


def _scripts():
    with open(FIXTURE, encoding="ascii") as f:
        return json.load(f)


def test_fixture_header():
    d = _scripts()
    h = d["header"]
    assert h["jvm_flags"] == "-XX:+UnlockExperimentalVMOptions -XX:hashCode=2"
    assert h["identity_hash_of_two_objects"] == "1,1" == "%d,%d" % (IDENTITY_HASH, IDENTITY_HASH)
    assert h["num_ops"] == sum(len(s["ops"]) for s in d["scripts"]) > 10000


@pytest.mark.parametrize("script", _scripts()["scripts"], ids=lambda s: s["id"])
def test_iteration_order_matches_jdk(script):
    for i, line in _replay(script):
        assert _digest(line) == script["orders_sha1_12"][i], (
            "%s: order differs from the JDK after op %d (%s): python gives %r"
            % (script["id"], i, script["ops"][i], line))


def test_fixture_exercises_tree_bins():
    """The scripts must reach treeified bins, tree removals, untreeify and re-treeify."""
    import cyber_detectives.compat.javahash as jh

    counts = {"tree": 0, "remove": 0, "untreeify": 0}
    orig_make, orig_rm = jh._make_tree_bin, jh._remove_tree_node

    def make(*a):
        counts["tree"] += 1
        return orig_make(*a)

    def rm(*a):
        r = orig_rm(*a)
        counts["remove"] += 1
        counts["untreeify"] += bool(r)
        return r

    jh._make_tree_bin, jh._remove_tree_node = make, rm
    try:
        for s in _scripts()["scripts"]:
            for _ in _replay(s):
                pass
    finally:
        jh._make_tree_bin, jh._remove_tree_node = orig_make, orig_rm
    assert counts["tree"] > 20 and counts["remove"] > 1000 and counts["untreeify"] > 10, counts


